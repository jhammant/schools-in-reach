def esc(value):
    return escape(str(value), quote=True)


def slug(value):
    text = unicodedata.normalize("NFKD", str(value).replace("&", " and "))
    text = text.encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")[:80].rstrip("-") or "school"


def shorten(text, limit):
    if len(text) <= limit:
        return text
    prefix = text[:limit - 1].rsplit(" ", 1)[0]
    # A single overlong token cannot be shortened without splitting it.
    if " " not in text[:limit - 1]:
        return "…"
    return prefix.rstrip(" ,;:–—-") + "…"


def school_title(name):
    title = f"{name} admissions, catchment & Ofsted | Schools in Reach"
    if len(title) > 70:
        title = title.removesuffix(" | Schools in Reach")
    return shorten(title, 70)


def safe_url(value):
    if not isinstance(value, str):
        return ""
    parsed = urlsplit(value)
    return value if parsed.scheme in ("http", "https") and parsed.netloc else ""


def number(value):
    return isinstance(value, (float, int)) and not isinstance(value, bool) and math.isfinite(value)


def present(value):
    return value is not None and value != "" and value not in ("SUPP", "NE", "NP", "NA", "N/A", "null")


def fmt(value):
    if not present(value):
        return "Not published"
    return f"{value:,}" if number(value) else str(value)


def read_json(path, required=False):
    if not path.exists() and not required:
        return {}
    with path.open(encoding="utf-8") as stream:
        return json.load(stream)



def load_crosslinks(path):
    """Read optional editorial links once per build; bad exports never block pages."""
    try:
        doc = read_json(Path(path))
        tm = doc["termminder"]
        base = tm["base"]
        if base != "https://www.termminder.com":
            return {}
        links = {}
        for group, prefix in (("schools", "/uk/schools/"), ("councils", "/uk/term-dates/")):
            mappings = tm[group]
            if not isinstance(mappings, dict):
                return {}
            if any(not isinstance(value, str) or not re.fullmatch(re.escape(prefix) + r"[A-Za-z0-9_-]+/", value)
                   for value in mappings.values()):
                return {}
            links[group] = {key: base + value for key, value in mappings.items()}
        return links
    except (OSError, ValueError, KeyError, TypeError):
        return {}


def data_date(*documents):
    dates = []
    for doc in documents:
        for key in ("generated", "data_as_at"):
            value = doc.get(key)
            values = value.values() if isinstance(value, dict) else [value]
            for item in values:
                if isinstance(item, str):
                    try:
                        dates.append(date.fromisoformat(item[:10]).isoformat())
                    except ValueError:
                        pass
    return max(dates, default="")


def phase(s):
    raw = str(s.get("phase") or "").lower()
    kind = str(s.get("type") or "").lower()
    group = str(s.get("type_group") or "").lower()
    if "special" in kind + group or "pupil referral" in kind or "alternative provision" in kind:
        return "Special and alternative provision"
    if "middle" in raw:
        return "Middle"
    for word, label in (("nursery", "Nursery"), ("primary", "Primary"), ("secondary", "Secondary"), ("all-through", "All-through"), ("all through", "All-through"), ("16", "Sixth form / 16+")):
        if word in raw:
            return label
    low, high = s.get("age_low"), s.get("age_high")
    if "college" in group or (number(low) and low >= 16):
        return "Sixth form / 16+"
    if number(high) and high <= 11:
        return "Primary"
    if number(low) and low >= 10:
        return "Secondary"
    if number(high) and high >= 16:
        return "All-through"
    return "Other"


