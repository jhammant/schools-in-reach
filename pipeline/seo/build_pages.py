def pupil_rows(s, census, characteristics, char_doc):
    rows = []
    if number(characteristics.get("headcount")):
        pupils = characteristics["headcount"]
        rows.append(("Pupils", fmt(pupils), char_doc.get("time_period") or "Latest census"))
    elif number(census.get("pupils")):
        pupils = census["pupils"]
        rows.append(("Pupils", fmt(pupils), census.get("year") or census.get("census_date") or "Latest census"))
    else:
        pupils = s.get("pupils")
        if number(pupils):
            rows.append(("Pupils", fmt(pupils), s.get("census_date") or "Published school roll"))
    for label, char_value, key in (
        ("Eligible for free school meals", (characteristics.get("fsm") or {}).get("eligible_pct"), "fsm_pct"),
        ("English as an additional language", (characteristics.get("language") or {}).get("eal_pct"), "eal_pct"),
        ("SEN support", None, "sen_support_pct"),
        ("Education, health and care (EHC) plan", None, "ehcp_pct"),
    ):
        value = char_value if number(char_value) else census.get(key)
        vintage = char_doc.get("time_period") if number(char_value) else census.get("year")
        if key == "fsm_pct" and not number(char_value):
            vintage = census.get("fsm_pct_source") or vintage
        if number(value):
            rows.append((label, f"{value:g}%", vintage or "Year not published"))
    return pupils, rows


def table(headers, rows, caption="", css=""):
    if not rows:
        return ""
    return (f'<table class="responsive {esc(css)}">' + (f"<caption>{esc(caption)}</caption>" if caption else "")
            + "<thead><tr>" + "".join(f'<th scope="col">{esc(h)}</th>' for h in headers) + "</tr></thead><tbody>"
            + "".join("<tr>" + "".join(f'<td data-label="{esc(h)}"><div>{v}</div></td>' for h, v in zip(headers, row)) + "</tr>" for row in rows) + "</tbody></table>")


def distance_text(y):
    distances = year_distances(y)
    groups = list(dict.fromkeys((y.get("groups") or []) + list(distances) + all_offered(y)))
    parts = []
    for group in groups:
        value = distances.get(group)
        text = f"{value:.2f} mi" if number(value) and not is_open_band(value) else ""
        if group in all_offered(y) or is_open_band(value):
            text = (text + "; " if text else "") + "All offered"
        if text:
            parts.append((f"{group}: " if group != "All" else "") + text)
    return parts


def latest_distance(rec):
    years = rec.get("years") or {}
    if not years:
        return ""
    year = max(years)
    parts = distance_text(years[year])
    return f"{year}: " + "; ".join(parts) if parts else ""


def admissions_html(rec, council, doc, school):
    name, nation = council["name"], council["nation"]
    html = "<h2>Admissions</h2>"
    if not has_admissions(rec):
        if any(has_admissions(r) for r in admissions_records(doc).values()):
            text = f"Admissions figures for this school aren't loaded yet. {name} has figures for some other schools; a missing record does not establish whether this school had spare places."
        else:
            text = f"{name} council's admissions figures aren't loaded yet."
        html += f"<p>{esc(text)}</p>"
        if "independent" in str(school.get("type_group", school.get("type", ""))).lower():
            html += "<p>This is an independent school. It sets its own admissions process, including any assessments, interviews and fees; contact the school directly.</p>"
    else:
        rows = []
        for year, y in sorted(rec["years"].items(), reverse=True):
            distances = distance_text(y)
            cells = "".join(f'<span class="distance">{esc(t)}</span>' for t in distances) or "Not published"
            rows.append([esc(year), cells, esc(fmt(y.get("pan"))), esc(fmt(y.get("applications"))), esc(fmt(y.get("total_offers")))])
        html += table(["Entry year", "Last distance offered", "Places (PAN)", "Applications", "Offers"], rows, "Published admissions history", "admissions")
        year = max(rec["years"])
        y = rec["years"][year]
        finite = [(g, v) for g, v in year_distances(y).items() if number(v) and not is_open_band(v)]
        if len(finite) == 1:
            group, value = finite[0]
            band = f" in band {group}" if group != "All" else ""
            html += f"<p>{esc(f'In {year} the last place offered on distance{band} went to a child living {value:.2f} miles away.')}</p>"
        elif finite:
            low, high = min(v for _, v in finite), max(v for _, v in finite)
            html += f"<p>{esc(f'In {year} the last distances offered ranged from {low:.2f} to {high:.2f} miles across the published bands or admission groups.')}</p>"
        if all_offered(y):
            html += "<p>“All offered” means the published group had places for all eligible applicants; its distance is not a cut-off for admission.</p>"
        html += '<p class="note">Distances are in miles (mi), as in the map app. PAN is the published admission number. Bands and admission groups have separate criteria; school-wide places, applications and offers are not counts for each band. Past offers are a guide, not a promise of a place.</p>'
        if doc.get("distance_notes"):
            html += f'<p class="note">{esc(doc["distance_notes"])}</p>'
        # Preserve school-specific exceptions (nodal points, faith or selective queues).
        notes = y.get("notes") or []
        if isinstance(notes, str):
            notes = [notes]
        if notes:
            html += '<p class="note">' + esc(" ".join(notes)) + "</p>"
    if nation in ("Scotland", "Wales"):
        html += f"<p>{esc(nation)} uses catchment areas and other admission priorities. A nearby address alone does not establish eligibility; check the council’s catchment boundary and school criteria.</p>"
    elif nation == "Northern Ireland":
        html += "<p>Northern Ireland’s post-primary admissions are not distance-based. Schools use their published criteria, and some grammar schools use entrance assessments. We do not provide chance estimates here.</p>"
    url = next((safe_url(obj.get(k)) for obj in (council, doc) for k in ("admissions_url", "admissions_page", "url") if safe_url(obj.get(k))), "")
    if not url:
        url = next((safe_url(s.get("url")) for s in doc.get("sources", []) if re.search(r"admission|allocation|offer", str(s.get("title", "")), re.I) and safe_url(s.get("url"))), "")
    if url:
        html += f'<p><a href="{esc(url)}">{esc(name)} admissions information and published allocations</a></p>'
    return html


class HeadMetadata(HTMLParser):
    def __init__(self, text):
        super().__init__()
        self.adsense = ""
        self.image = ""
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
