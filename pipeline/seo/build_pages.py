# Mirrors OPEN_BAND_MILES in site/js/admissions.js: a published "cut-off" beyond this
# (e.g. 7.2 or 350 mi) means everyone in that band was offered, not a real boundary.
OPEN_BAND_MILES = 3


def year_distances(y):
    value = y.get("max_distance")
    return value if isinstance(value, dict) else {"All": value}


def is_open_band(value):
    return number(value) and value > OPEN_BAND_MILES


def all_offered(y):
    value = y.get("all_offered")
    if isinstance(value, list):
        return value
    return (y.get("groups") or list(year_distances(y))) if value else []


def has_admissions(rec):
    return any(any(number(y.get(k)) for k in ("pan", "applications", "total_offers"))
               or any(number(v) for v in year_distances(y).values()) or bool(all_offered(y))
               for y in rec.get("years", {}).values())


OFSTED_GRADES = ("Outstanding", "Good", "Requires improvement", "Inadequate")
# Ofsted report cards (from November 2025) grade each area on this scale, with no overall grade.
REPORT_CARD_GRADES = ("Exceptional", "Strong standard", "Expected standard", "Needs attention", "Urgent improvement")


def uk_date(value):
    """2025-01-22 -> 22 January 2025; anything unparseable is returned unchanged."""
    try:
        d = date.fromisoformat(str(value)[:10])
    except (TypeError, ValueError):
        return value
    return f"{d.day} {d.strftime('%B %Y')}"


def area_summary(facts, grades=OFSTED_GRADES, fallback="Area judgements published", prefix=""):
    """One line for inspections that grade each area but give no overall judgement."""
    counts = Counter(v for _, v in facts if v in grades)
    if not counts:
        return fallback
    if len(counts) == 1:
        grade, n = counts.popitem()
        return prefix + (f"{grade} in all {n} graded areas" if n > 1 else f"{grade} in its graded area")
    parts = [f"{g} in {counts[g]} area{'s' if counts[g] > 1 else ''}" for g in grades if counts[g]]
    return prefix + ", ".join(parts)


def ofsted_facts(rec):
    latest = rec.get("latest") or {}
    facts = []
    if latest.get("kind") == "report_card":
        facts = [(k.replace("_", " ").capitalize(), fmt(v)) for k, v in latest.get("report_card", {}).items() if present(v) and v != "Not applicable"]
        summary = area_summary(facts, REPORT_CARD_GRADES, "Report card", "Report card: ") if facts else ""
        return summary, uk_date(latest.get("date")), facts
    judgments = latest.get("judgements") or {}
    overall = judgments.get("overall_effectiveness") or latest.get("overall_effectiveness")
    if latest.get("kind") == "ungraded":
        overall = latest.get("outcome")
        prior = rec.get("last_graded") or rec.get("previous") or {}
        grade = (prior.get("judgements") or {}).get("overall_effectiveness") or prior.get("overall_effectiveness")
        if grade and grade != "Not judged":
            facts.append(("Last graded overall judgement", f"{grade} ({uk_date(prior.get('date')) or 'date not published'})"))
    for key, value in judgments.items():
        if present(value) and value not in ("Not judged", "Not applicable"):
            facts.append((key.replace("_", " ").capitalize(), ("Yes" if value else "No") if isinstance(value, bool) else str(value)))
    if overall == "Not judged":
        overall = None
    return overall or (area_summary(facts) if facts else ""), uk_date(latest.get("date")), facts


