def school_path(s):
    urn = str(s["urn"])
    if not re.fullmatch(r"[0-9]+", urn):
        raise ValueError(f"Invalid school identifier: {urn!r}")
    return f'/school/{urn}-{slug(s["name"])}/'


def coordinates(s):
    lat, lon = s.get("lat"), s.get("lon")
    if number(lat) and number(lon) and -90 <= lat <= 90 and -180 <= lon <= 180:
        return lat, lon
    return None


def proximity(a, b):
    pa, pb = coordinates(a), coordinates(b)
    if not pa or not pb:
        return math.inf
    lat1, lon1, lat2, lon2 = map(math.radians, (*pa, *pb))
    return math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2


